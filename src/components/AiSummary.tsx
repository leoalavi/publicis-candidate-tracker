"use client";

import { useState } from "react";
import { cardClass, primaryButtonClass, secondaryButtonClass } from "./ui";
import { apiRequest } from "@/lib/api-client";
import { formatDate } from "@/lib/candidates";
import type { AiSummaryResult } from "@/lib/types";

type Props = {
  candidateId: string;
  hasResumeText: boolean;
  initialSummary: string | null;
  initialGeneratedAt: string | null;
  initialIsStale: boolean;
};

// The "AI summary" card on the candidate detail page.
export function AiSummary({ candidateId, hasResumeText, initialSummary, initialGeneratedAt, initialIsStale }: Props) {
  const [summary, setSummary] = useState(initialSummary);
  const [generatedAt, setGeneratedAt] = useState(initialGeneratedAt);
  const [isStale, setIsStale] = useState(initialIsStale);
  const [isGenerating, setIsGenerating] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function handleGenerate() {
    setIsGenerating(true);
    setError(null);
    try {
      const result = await apiRequest<AiSummaryResult>(`/api/candidates/${candidateId}/summary`, { method: "POST" });
      setSummary(result.ai_summary);
      setGeneratedAt(result.ai_summary_generated_at);
      setIsStale(result.ai_summary_is_stale);
    } catch (err) {
      setError((err as Error).message);
    } finally {
      setIsGenerating(false);
    }
  }

  return (
    <section className={cardClass} aria-labelledby="ai-summary-heading" aria-busy={isGenerating}>
      <div className="mb-3 flex flex-wrap items-center justify-between gap-2">
        <h2 id="ai-summary-heading" className="text-lg font-semibold">
          AI summary
          <span className="ml-2 rounded-full bg-violet-100 px-2 py-0.5 align-middle text-xs font-medium text-violet-800">
            AI-generated
          </span>
        </h2>
        {hasResumeText && (
          <button
            type="button"
            onClick={handleGenerate}
            disabled={isGenerating}
            className={summary ? secondaryButtonClass : primaryButtonClass}
          >
            {isGenerating ? "Generating…" : summary ? "Regenerate summary" : "Generate AI summary"}
          </button>
        )}
      </div>

      {!hasResumeText && (
        <p className="text-sm text-slate-600">This candidate has no resume or cover letter text to summarise.</p>
      )}

      {isGenerating && (
        <p className="text-sm text-slate-600" role="status">Generating summary… this usually takes a few seconds.</p>
      )}

      {error && (
        <p className="mb-3 rounded-md border border-red-200 bg-red-50 p-3 text-sm text-red-800" role="alert">
          {error}
        </p>
      )}

      {summary && !isGenerating && (
        <div className="space-y-2">
          {isStale && (
            <p className="rounded-md border border-amber-200 bg-amber-50 p-2 text-sm text-amber-900">
              The resume has changed since this summary was generated, so it may be out of date. Regenerate it to update.
            </p>
          )}
          <p className="whitespace-pre-wrap text-sm leading-6">{summary}</p>
          <p className="text-xs text-slate-500">
            Generated by AI{generatedAt ? ` on ${formatDate(generatedAt)}` : ""}. It may contain mistakes. Check it
            against the resume before relying on it.
          </p>
        </div>
      )}

      {hasResumeText && !summary && !isGenerating && !error && (
        <p className="text-sm text-slate-600">No summary yet. Generate one from the resume text above.</p>
      )}
    </section>
  );
}
